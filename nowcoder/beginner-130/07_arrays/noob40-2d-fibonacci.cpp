#include<bits/stdc++.h>
using namespace std;
long long a[1000][1000]; // 定义全局数组，存储数列各项值
//注意，这里故意把数组开大了一倍，这样我们就可以假装数组的第一个元素为 a[1] 了

int main(){
    int n,m; // 定义变量n和m，分别表示二维数组的行数和列数
    cin>>n>>m; // 读取输入的行数n和列数m
    
    // 使用递推公式计算每一项的值
    for(int i=1;i<=n;i++){ // 遍历每一行
        for(int j=1;j<=m;j++){ // 遍历每一列
            if(i==1&&j==1) a[i][j]=1%1000000007; // 递推式1：第一行第一列的值为1
            else if(i==1) a[i][j]=a[i][j-1]%1000000007; // 递推式2：第一行的值等于左边相邻的值
            else if(j==1) a[i][j]=a[i-1][j]%1000000007; // 递推式3：第一列的值等于上方相邻的值
            else a[i][j]=(a[i-1][j]+a[i][j-1])%1000000007; // 递推式4：其他位置的值等于上方值加左边值
        }
    }
    
    cout<<a[n][m]; // 输出二维数组第n行第m列的值
    return 0; // 程序正常结束
}